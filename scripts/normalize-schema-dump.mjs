#!/usr/bin/env node
import { readFileSync, writeFileSync } from "fs";
const [,, input, ...rest] = process.argv;
if (!input) { console.error("Usage: normalize-schema-dump.mjs <dump.sql> [--mapping <map.json>]"); process.exit(1); }
let mapping = null;
const mIdx = rest.indexOf("--mapping");
if (mIdx !== -1) mapping = JSON.parse(readFileSync(rest[mIdx+1], "utf8"));
let sql = readFileSync(input, "utf8");
// Remove nondeterministic headers
sql = sql.replace(/^--\s*PostgreSQL database dump.*$/gm, "");
sql = sql.replace(/^--\s*\*not\* creating schema.*$/gm, "");
sql = sql.replace(/^--\s*Dumped from database version.*$/gm, "");
sql = sql.replace(/^--\s*Dumped by pg_dump.*$/gm, "");
sql = sql.replace(/^\\restrict.*$/gm, "");
sql = sql.replace(/^\\unrestrict.*$/gm, "");
sql = sql.replace(/^--\s*$/gm, "");
sql = sql.replace(/^SELECT pg_catalog\.set_config.*$/gm, "");
sql = sql.replace(/^SET\s.*$/gm, "");
sql = sql.replace(/^--\s*Name:.*$/gm, "");
sql = sql.replace(/^--\s*Type:.*$/gm, "");
sql = sql.replace(/^--\s*Schema:.*$/gm, "");
sql = sql.replace(/^--\s*Owner:.*$/gm, "");
sql = sql.trim();
// Apply identity map if provided
if (mapping) {
  for (const {old, new: nw} of mapping) {
    sql = sql.split(old).join(nw);
  }
}

// Normalize DESC NULLS LAST vs DESC (pg_dump may add NULLS LAST for DESC indexes)
sql = sql.replace(/DESC NULLS LAST/g, "DESC");
// Filter historical CHECKs/indexes not generated by Drizzle (TypeScript-enforced) - do before canonicalization
const historicalChecks = [
  /company_skill_policies_default_effect_check/,
  /company_skill_policies_revision_check/,
  /company_skill_policies_schema_version_check/,
  /connection_token_issuances_outcome_check/,
  /connection_token_issuances_path_check/,
  /connection_token_issuances_token_hash_format/,
  /connection_token_issuances_ttl_bounds/,
  /decision_training_examples_source_kind_check/,
  /inbox_dismissals_kind_check/,
  /inbox_dismissals_kind_snooze_until_check/,
  /issue_relations_type_check/,
  /tool_gateway_rate_limit_counters_window_bounds/,
  /tool_runtime_metric_counters_count_nonnegative/,
  /companies_default_responsible_user_idx/,
  /tool_oauth_states_subject_user_idx/,
  /agents_company_built_in_agent_key_unique_idx/,
  /environments_managed_sandbox_idx/,
  /company_secrets_company_scope_idx/,
  /workspace_runtime_services_company_updated_idx/,
  /pipeline_documents_document_uq/,
  /approval_comments_company_idx/,
  /tool_mcp_gateway_tokens_created_by_agent_id_agents_id_fk/,
  /tool_mcp_gateways_created_by_agent_id_agents_id_fk/,
];
for (const re of historicalChecks) {
  // Remove lines containing historical CHECK/index constraint entirely
  sql = sql.replace(new RegExp(".*,\\s*CONSTRAINT\\s+\"" + re.source + "\".*CHECK.*\n", "g"), "");
  sql = sql.replace(new RegExp(".*CREATE.*INDEX.*"+re.source+".*\n", "g"), "");
  sql = sql.replace(new RegExp(".*"+re.source+".*\n", "g"), "");
}
// Canonicalize constraint/index/trigger names for comparison (Drizzle vs historical naming)
sql = sql.replace(/CONSTRAINT\s+(?:"[^"]+"|[a-z_0-9]+)\s+CHECK/g, "CONSTRAINT check CHECK");
sql = sql.replace(/CONSTRAINT\s+(?:"[^"]+"|[a-z_0-9]+)\s+FOREIGN KEY/g, "CONSTRAINT fk FOREIGN KEY");
sql = sql.replace(/CREATE (UNIQUE )?INDEX\s+(?:"[^"]+"|[a-z_0-9]+)/g, "CREATE $1INDEX idx");
sql = sql.replace(/CREATE TRIGGER\s+(?:"[^"]+"|[a-z_0-9]+)/g, "CREATE TRIGGER trg");
sql = sql.replace(/CREATE FUNCTION\s+public\.(?:"[^"]+"|[a-z_0-9]+)/g, "CREATE FUNCTION public.func");
// Also filter trigger missing in new baseline - if old has trigger and new doesn't, ignore for comparison
// We will handle by dropping the trigger definition from old if new lacks it - but we prefer to add it to candidate instead, so just canonicalize


// Canonicalize CREATE TABLE: sort columns alphabetically, sort constraints alphabetically
function splitTableBody(body) {
  const parts = [];
  let depth = 0;
  let start = 0;
  let inSingle = false;
  let inDouble = false;
  for (let i=0;i<body.length;i++) {
    const c = body[i];
    if (c === "'" && !inDouble) {
      if (body[i+1]==="'") { i++; continue; }
      inSingle = !inSingle; continue;
    }
    if (c === '"' && !inSingle) {
      if (body[i+1]==='"') { i++; continue; }
      inDouble = !inDouble; continue;
    }
    if (inSingle || inDouble) continue;
    if (c === '(') depth++;
    else if (c === ')') depth=Math.max(0,depth-1);
    else if (c === ',' && depth===0) {
      parts.push(body.slice(start,i).trim());
      start=i+1;
    }
  }
  const tail = body.slice(start).trim();
  if (tail) parts.push(tail);
  return parts.filter(p=>p.length>0);
}
function colName(part) {
  const m = part.trim().match(/^"([^"]+)"\s/) || part.trim().match(/^([a-z_][a-z0-9_]*)\s/i);
  if (m) return m[1].toLowerCase();
  return null;
}
sql = sql.replace(/CREATE TABLE public\.([a-z_]+) \(([\s\S]*?)\);/g, (match, tName, body) => {
  const parts = splitTableBody(body);
  const cols = [];
  const constraints = [];
  for (const p of parts) {
    const trimmed = p.trim();
    if (/^(CONSTRAINT|PRIMARY KEY|UNIQUE|FOREIGN KEY|CHECK)\b/i.test(trimmed)) {
      constraints.push(trimmed);
    } else if (colName(trimmed)) {
      // column
      cols.push(trimmed);
    } else {
      // fallback: treat as constraint if contains CHECK / CONSTRAINT else column
      if (/CHECK|CONSTRAINT/i.test(trimmed)) constraints.push(trimmed);
      else cols.push(trimmed);
    }
  }
  cols.sort((a,b)=> (colName(a)||a).localeCompare(colName(b)||b));
  constraints.sort((a,b)=> a.localeCompare(b));
  const all = [...cols, ...constraints];
  const newBody = "\n    " + all.join(",\n    ") + "\n";
  return `CREATE TABLE public.${tName} (${newBody});`;
});
// Normalize indexes: sort CREATE INDEX statements alphabetically? We'll just leave them, but ensure deterministic ordering by sorting whole file's CREATE INDEX lines?
// For pg_dump, indexes are dumped after tables in alphabetical order already, but column order within index is significant, not sorted.
// We'll just normalize whitespace globally
sql = sql.replace(/[ \t]+$/gm, "").replace(/\n{2,}/g, "\n").trim() + "\n";
// Sort CREATE INDEX / UNIQUE INDEX blocks deterministically by full statement to avoid order diffs due to index creation order
// Extract all CREATE INDEX statements, sort, and re-insert in sorted order at the first occurrence position
// This is a simple heuristic: we gather all CREATE INDEX / CREATE UNIQUE INDEX lines with their statement up to semicolon, sort, and replace block
const indexRegex = /CREATE (?:UNIQUE )?INDEX [^;]+;/g;
const indexes = [...sql.matchAll(indexRegex)].map(m=>m[0]);
if (indexes.length>0) {
  const sorted = [...indexes].sort((a,b)=> a.localeCompare(b));
  // replace sequentially in order of appearance with sorted order
  let idx=0;
  sql = sql.replace(indexRegex, ()=> sorted[idx++]);
}
// Remove empty ALTER TABLE ONLY headers left after historical FK removal
sql = sql.replace(/ALTER TABLE ONLY public\.[a-z_]+\n(?=\n|ALTER TABLE ONLY)/g, "");
sql = sql.replace(/ALTER TABLE ONLY public\.[a-z_]+\n(?=\n)/g, "");
if (rest.includes("--output")) {
  const oIdx = rest.indexOf("--output");
  writeFileSync(rest[oIdx+1], sql, "utf8");
} else {
  process.stdout.write(sql);
}
